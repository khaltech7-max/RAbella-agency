export function getRoleDisplayLabel(role: UserRole, tenantRef?: string): string {
  switch (role) {
    case 'super_admin':
      return 'Super Admin';
    case 'owner':
      return 'Super Admin (Owner)';
    case 'administrator':
      return 'Administrator';
    case 'property_manager':
      return 'Property Manager';
    case 'accountant':
      return 'Accountant';
    case 'caretaker':
      return 'Caretaker';
    case 'maintenance_staff':
      return 'Maintenance Staff';
    case 'tenant':
    default:
      return tenantRef ? `Tenant (Ref: ${tenantRef})` : 'Tenant';
  }
}

export function isManagementRole(role: UserRole): boolean {
  return role !== 'tenant';
}

export function getAllowedPagesForRole(role: UserRole): NavPageId[] {
  switch (role) {
    case 'super_admin':
    case 'owner':
    case 'administrator':
      return [
        'dashboard',
        'payments',
        'units',
        'messages',
        'maintenance',
        'properties',
        'tenants',
        'invoices',
        'expenses',
        'reports',
        'staff',
      ];
    case 'property_manager':
      return [
        'dashboard',
        'payments',
        'units',
        'messages',
        'maintenance',
        'properties',
        'tenants',
        'invoices',
        'expenses',
        'reports',
      ];
    case 'accountant':
      return ['dashboard', 'payments', 'invoices', 'expenses', 'reports'];
    case 'caretaker':
      return ['dashboard', 'properties', 'units', 'maintenance'];
    case 'maintenance_staff':
      return ['dashboard', 'maintenance'];
    case 'tenant':
    default:
      return ['dashboard', 'payments', 'tenants', 'maintenance', 'messages', 'invoices'];
  }
}

export function getDefaultPageForRole(role: UserRole): NavPageId {
  switch (role) {
    case 'maintenance_staff':
      return 'maintenance';
    case 'accountant':
      return 'payments';
    case 'tenant':
      return 'tenants';
    default:
      return 'dashboard';
  }
}

