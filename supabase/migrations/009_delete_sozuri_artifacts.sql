-- =============================================================================
-- SQL SCRIPT: COMPLETE REMOVAL & DELETION OF ALL SOZURI ARTIFACTS
-- Run this script in the Supabase SQL Editor (Dashboard > SQL Editor > New query)
-- =============================================================================

BEGIN;

-- 1. Drop any legacy columns added specifically for Sozuri
ALTER TABLE IF EXISTS public.sms_notification_settings
  DROP COLUMN IF EXISTS sozuri_project;

-- 2. Reset any sender_id or provider configured as 'Sozuri' to default
UPDATE public.sms_notification_settings
SET sender_id = 'ARABELLA',
    updated_at = NOW()
WHERE sender_id ILIKE '%sozuri%';

-- 3. Delete any SMS logs generated by or referencing Sozuri
DELETE FROM public.sms_logs
WHERE provider ILIKE '%sozuri%'
   OR api_response::text ILIKE '%sozuri%';

-- 4. Drop any dedicated Sozuri webhook, templates, or tracking tables if they exist
DROP TABLE IF EXISTS public.sozuri_webhooks CASCADE;
DROP TABLE IF EXISTS public.sozuri_whatsapp_templates CASCADE;
DROP TABLE IF EXISTS public.sozuri_whatsapp_channels CASCADE;
DROP TABLE IF EXISTS public.sozuri_logs CASCADE;

-- 5. Drop any Sozuri-related database functions or triggers if present
DROP FUNCTION IF EXISTS public.handle_sozuri_webhook CASCADE;
DROP FUNCTION IF EXISTS public.sozuri_sms_dispatcher CASCADE;

COMMIT;

-- 6. Verification Queries (Run to confirm clean removal)
-- Should return 0 rows
SELECT count(*) AS remaining_sozuri_logs
FROM public.sms_logs
WHERE provider ILIKE '%sozuri%'
   OR api_response::text ILIKE '%sozuri%';

-- Verify current SMS settings
SELECT id, environment, sender_id, master_enabled, updated_at
FROM public.sms_notification_settings
WHERE id = 'default';
